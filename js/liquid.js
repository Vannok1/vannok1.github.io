// Physical model of beer in a glass seen from the side (the phone screen is the glass,
// its top edge is the rim). Everything is in SI units.
//
//  * Free surface: always perpendicular to the in-plane component of gravity; its height
//    is found from volume conservation (area below the line in the rectangle).
//  * Sloshing: linear modal theory for a rectangular tank (Ibrahim, "Liquid Sloshing
//    Dynamics"), modes cos(nπx/L) with ω² = g·k·tanh(k·h) + (σ/ρ)·k³, excited by the
//    phone's linear acceleration and by fast in-plane rotation. Foam adds damping
//    (Sauret et al., "Damping of liquid sloshing by foams", Phys. Fluids 2015).
//  * Drinking: liquid above the rim flows out following Torricelli's law per unit rim
//    length, which integrates to the classic weir law Q ∝ √(2g)·h^{3/2}.
//  * Foam: generated by pouring (∝ impact speed) and shaking (CO₂ nucleation), decays
//    with a style-dependent half-life, damps waves, and is drunk first.

import { solveLevel, chordExtent } from './geometry.js';
import { G } from './orientation.js';

export const NMODES = 20;
export const WAVE_SAMPLES = 256;
const SIGMA_RHO = 4.2e-5; // surface tension / density of beer, m³/s²
const NU = 1.6e-6; // kinematic viscosity of beer, m²/s
const CD = 0.62; // discharge coefficient of a sharp rim
const DRINK_SCALE = 0.16; // air must get in through the same opening (glugging) and lips limit the flow
const FOAM_LIQUID = 0.1; // liquid fraction of foam
const FOAM_FLOOR = 0.0012; // thin film of foam that survives on a beer, m
const SHAKE_FOAM = 0.006; // area fraction / s per (m/s²)^1.5
const POUR_FOAM = 0.27;
const PITCH_FOLLOW = 0.35; // fraction of a fast rotation the surface follows at first
const PI = Math.PI;

const clamp = (x, a, b) => (x < a ? a : x > b ? b : x);
const smoothstep = (a, b, x) => {
  const t = clamp((x - a) / (b - a), 0, 1);
  return t * t * (3 - 2 * t);
};
const wrapAngle = (a) => Math.atan2(Math.sin(a), Math.cos(a));

export class LiquidSim {
  constructor({ width, height, beer }) {
    this.W = width;
    this.H = height;
    this.beer = beer;
    this.vol = 0;
    this.foamVol = 0;
    this.carb = 1;
    this.foamAge = 0;
    this.ux = 0;
    this.uy = 1;
    this.gIn = G;
    this.gz = 0;
    this.theta = 0;
    this.thetaRate = 0;
    this.a = new Float64Array(NMODES + 1);
    this.v = new Float64Array(NMODES + 1);
    this.c = -height / 2;
    this.cf = -height / 2;
    this.sMin = -width / 2;
    this.sMax = width / 2;
    this.waveRange = Math.hypot(width, height) / 2;
    this.wave = new Float32Array(WAVE_SAMPLES);
    this.shake = 0;
    this.outflow = 0; // beer leaving over the rim, area fraction per second (smoothed)
    this.foamOutflow = 0;
    this.drunkThisGlass = 0;
    this.glasses = 0;
    this.cloud = 0; // micro-bubble cloud after pouring (0..1)
    this.cloudFront = 1; // how far the settling front has risen (0 bottom .. 1 top)
    this.time = 0;
    this.events = [];
    this.pour = {
      active: false,
      target: 0,
      rate: 0,
      flow: 0,
      visible: false,
      x0: 0,
      y0: 0,
      len: 0,
      s0: 0,
      wall: false,
    };
    this.ready = false;
  }

  get area() {
    return this.W * this.H;
  }
  get fill() {
    return this.vol / this.area;
  }
  get foamFill() {
    return this.foamVol / this.area;
  }
  get foamThickness() {
    return Math.max(0, this.cf - this.c);
  }

  /** Resize the glass keeping fill fractions (e.g. the browser toolbar appears). */
  setSize(width, height) {
    if (width === this.W && height === this.H) return;
    const k = (width * height) / this.area;
    this.vol *= k;
    this.foamVol *= k;
    this.W = width;
    this.H = height;
    this.waveRange = Math.hypot(width, height) / 2;
    this.a.fill(0);
    this.v.fill(0);
    this.ready = false;
  }

  setBeer(beer) {
    this.beer = beer;
  }

  /** Start pouring a fresh beer from the tap. */
  startPour({ targetFill = 0.68, seconds = 4.4 } = {}) {
    if (this.vol < 0.05 * this.area) {
      // fresh glass → fresh carbonation
      this.carb = 1;
      this.drunkThisGlass = 0;
    }
    this.pour.active = true;
    this.pour.target = targetFill * this.area;
    this.pour.rate = (targetFill * this.area) / seconds;
    this.cloudFront = 0;
  }

  stopPour() {
    this.pour.active = false;
  }

  /** Instantly set the content (used for tests and the very first frame). */
  setContent(fill, foamFill = 0) {
    this.vol = clamp(fill, 0, 1) * this.area;
    this.foamVol = clamp(foamFill, 0, 1) * this.area;
    this.a.fill(0);
    this.v.fill(0);
  }

  etaAt(s) {
    const R = this.waveRange;
    const f = ((s + R) / (2 * R)) * (WAVE_SAMPLES - 1);
    if (f <= 0) return this.wave[0];
    if (f >= WAVE_SAMPLES - 1) return this.wave[WAVE_SAMPLES - 1];
    const i = f | 0;
    const t = f - i;
    return this.wave[i] * (1 - t) + this.wave[i + 1] * t;
  }

  /** Signed height of point p (relative to the glass centre) above the beer surface. */
  heightAboveBeer(px, py) {
    const s = this.uy * px - this.ux * py;
    return this.ux * px + this.uy * py - (this.c + this.etaAt(s));
  }

  /** Signed height above the top of the foam. */
  heightAboveFoam(px, py) {
    const s = this.uy * px - this.ux * py;
    return this.ux * px + this.uy * py - (this.cf + this.etaAt(s));
  }

  /**
   * Advance the simulation.
   * @param {number} dt seconds
   * @param {{g:{x,y,z}, acc:{x,y,z}}} input unit gravity and linear acceleration
   *        (device frame, spec sign) of the phone.
   */
  step(dt, input) {
    dt = clamp(dt, 0, 1 / 20);
    if (dt <= 0) return;
    this.time += dt;
    const hw = this.W / 2;
    const hh = this.H / 2;
    const A = this.area;
    const beer = this.beer;
    const g = input.g;
    const acc = input.acc || { x: 0, y: 0, z: 0 };

    // ---- 1. Gravity in the plane of the glass ---------------------------------------
    const m = Math.hypot(g.x, g.y);
    // Hysteresis keeps the surface steady when the phone lies flat (m → 0).
    let bx = -g.x + 0.05 * this.ux;
    let by = -g.y + 0.05 * this.uy;
    let bn = Math.hypot(bx, by) || 1;
    const ux = bx / bn;
    const uy = by / bn;
    const reliable = smoothstep(0.12, 0.35, m);
    const thetaNew = Math.atan2(ux, uy); // CCW rotation of the phone from upright
    let rateNew = this.ready ? wrapAngle(thetaNew - this.theta) / dt : 0;
    rateNew = clamp(rateNew, -40, 40);
    const prevRate = this.thetaRate;
    this.thetaRate += (rateNew - this.thetaRate) * Math.min(1, dt / 0.035);
    const dRate = (this.thetaRate - prevRate) * reliable;
    this.theta = thetaNew;
    this.ux = ux;
    this.uy = uy;
    const tx = uy;
    const ty = -ux;
    this.gIn = G * Math.max(m, 0.04);
    this.gz = g.z;

    // ---- 2. Shaking → foam, CO₂ release ----------------------------------------------
    const aMag = Math.hypot(acc.x, acc.y, acc.z || 0);
    const shakeInst = Math.max(0, aMag - 2.5);
    this.shake += (shakeInst - this.shake) * Math.min(1, dt / 0.25);
    if (shakeInst > 0 && this.vol > 0.01 * A) {
      const p = Math.pow(shakeInst, 1.5);
      const liquidFactor = clamp((this.vol / A) * 3, 0, 1);
      const df = SHAKE_FOAM * beer.foaminess * this.carb * p * liquidFactor * A * dt;
      this.addFoam(df);
      this.carb *= Math.exp(-0.004 * p * dt);
      this.cloud = Math.min(1, this.cloud + 0.04 * p * dt * this.carb);
      this.cloudFront = Math.min(this.cloudFront, 0.15);
    }
    // Beer slowly goes flat on its own (~half an hour).
    this.carb *= Math.exp(-dt / 2400);

    // ---- 3. Pouring -----------------------------------------------------------------
    this.stepPour(dt, hw, hh);

    // ---- 4. Foam decay ----------------------------------------------------------------
    {
      const chord0 = chordExtent(hw, hh, ux, uy, this.c);
      const Lf = chord0 ? chord0[1] - chord0[0] : this.W;
      const floor = this.vol > 0.02 * A ? FOAM_FLOOR * Lf : 0;
      const tau = beer.foamTau * (0.3 + 0.7 * Math.min(1, this.foamAge / 25));
      if (this.foamVol > floor) {
        const dec = ((this.foamVol - floor) * dt) / tau;
        this.foamVol -= dec;
        this.vol += dec * FOAM_LIQUID;
      } else if (this.vol <= 0.02 * A) {
        const dec = (this.foamVol * dt) / 1.5;
        this.foamVol -= dec;
      }
      this.foamAge += dt;
    }

    // Overfill: whatever does not fit in the glass runs over the rim.
    if (this.vol > A) {
      this.vol = A;
    }
    if (this.vol + this.foamVol > A) {
      this.foamVol = Math.max(0, A - this.vol);
    }

    // ---- 5. Free-surface level -------------------------------------------------------
    this.c = solveLevel(hw, hh, ux, uy, this.vol);
    this.cf = solveLevel(hw, hh, ux, uy, Math.min(A, this.vol + this.foamVol));
    let chord = chordExtent(hw, hh, ux, uy, this.c);
    if (!chord) {
      // Empty (or completely full): use the chord just above the lowest corner.
      chord = chordExtent(hw, hh, ux, uy, this.c + 1e-4) || [-hw, hw];
    }
    const L = Math.max(chord[1] - chord[0], 0.004);
    this.sMin = chord[0];
    this.sMax = chord[1];
    const hMean = clamp(this.vol / L, 0.0005, this.H * 2);

    // ---- 6. Sloshing modes ----------------------------------------------------------
    const at = acc.x * tx + acc.y * ty; // phone acceleration along the surface
    const au = acc.x * ux + acc.y * uy; // ... and along "up"
    const gEff = clamp(this.gIn + au * Math.max(m, 0.04), 0.3 * this.gIn, 2.5 * this.gIn);
    const foamDamp = 0.14 * Math.min(1, this.foamThickness / 0.015);
    const wMax = 2.2 / dt;
    const hasLiquid = this.vol > 0.0005 * A;
    for (let n = 1; n <= NMODES; n++) {
      const k = (n * PI) / L;
      const odd = n & 1;
      const shape = (4 * L) / (n * n * PI * PI);
      let w = Math.sqrt(gEff * k * Math.tanh(k * hMean) + SIGMA_RHO * k * k * k);
      if (w > wMax) w = wMax;
      let zeta = 0.012 + foamDamp + (2 * NU * k * k) / w + 0.004 * n;
      if (!hasLiquid) zeta = 0.9;
      if (zeta > 0.9) zeta = 0.9;
      const ceq = odd ? (at / gEff) * shape : 0;
      if (odd) this.v[n] -= PITCH_FOLLOW * shape * dRate;
      // Exact solution of the damped oscillator over dt (unconditionally stable).
      const x0 = this.a[n] - ceq;
      const v0 = this.v[n];
      const wd = w * Math.sqrt(1 - zeta * zeta);
      const e = Math.exp(-zeta * w * dt);
      const cs = Math.cos(wd * dt);
      const sn = Math.sin(wd * dt);
      const B = (v0 + zeta * w * x0) / wd;
      const x1 = e * (x0 * cs + B * sn);
      const v1 = e * (v0 * cs - (zeta * w * B + wd * x0) * sn);
      const lim = (0.75 * L) / (n * PI);
      this.a[n] = clamp(x1 + ceq, -lim, lim);
      this.v[n] = clamp(v1, -lim * w, lim * w);
    }

    // ---- 7. Sample the surface for rendering ----------------------------------------
    this.sampleWave(L, hMean);

    // ---- 8. Drinking / spilling over the rim -----------------------------------------
    this.stepSpill(dt, hw, hh, tx, ty);

    // ---- 9. Micro-bubble cloud after pouring settles bottom → top ---------------------
    if (!this.pour.active) {
      this.cloudFront = Math.min(1.3, this.cloudFront + dt / beer.settle);
      if (this.cloudFront >= 1.3) this.cloud *= Math.exp(-dt / 2);
    }

    // ---- 10. Glass finished? ---------------------------------------------------------
    if (this.vol < 0.012 * A && this.drunkThisGlass > 0.3 * A && !this.pour.active) {
      this.glasses++;
      this.drunkThisGlass = 0;
      this.events.push('finished');
    }
    this.ready = true;
  }

  addFoam(df) {
    if (df <= 0) return;
    const taken = Math.min(this.vol, df * FOAM_LIQUID);
    this.vol -= taken;
    const F = this.foamVol;
    this.foamVol += df;
    this.foamAge = (this.foamAge * F) / (F + df);
  }

  sampleWave(L, hMean) {
    const R = this.waveRange;
    const sMin = this.sMin;
    const clip = Math.max(0.002, Math.min(0.35 * L, 0.8 * hMean + 0.004));
    for (let i = 0; i < WAVE_SAMPLES; i++) {
      let s = -R + (2 * R * i) / (WAVE_SAMPLES - 1);
      if (s < this.sMin) s = this.sMin;
      if (s > this.sMax) s = this.sMax;
      const x = (s - sMin) / L;
      let eta = 0;
      // cos(nπx) via the Chebyshev recurrence: one cos per sample.
      const c1 = Math.cos(PI * x);
      let cPrev = 1;
      let cCur = c1;
      for (let n = 1; n <= NMODES; n++) {
        eta += this.a[n] * cCur;
        const cNext = 2 * c1 * cCur - cPrev;
        cPrev = cCur;
        cCur = cNext;
      }
      this.wave[i] = clip * Math.tanh(eta / clip);
    }
  }

  stepPour(dt, hw, hh) {
    const P = this.pour;
    const target = P.active ? P.rate : 0;
    P.flow += (target - P.flow) * Math.min(1, dt / (P.active ? 0.18 : 0.12));
    // once the tap is closed the thinning stream breaks up into drops
    if (P.flow < 1e-7 || (!P.active && P.flow < 0.06 * P.rate)) {
      P.flow = 0;
      P.flow = 0;
      P.visible = false;
      return;
    }
    const ux = this.ux, uy = this.uy;
    // The tap is above the middle of the rim; the stream falls along gravity (−u).
    const x0 = 0.08 * this.W;
    const y0 = hh;
    P.x0 = x0;
    P.y0 = y0;
    const dy = -uy;
    if (dy > -0.15) {
      // Glass upside-down / on its side: the beer misses it.
      P.visible = false;
      if (P.active && this.vol >= P.target) P.active = false;
      return;
    }
    const dx = -ux;
    let tWall = Infinity;
    if (dx > 1e-6) tWall = (hw - x0) / dx;
    else if (dx < -1e-6) tWall = (-hw - x0) / dx;
    const tBottom = (2 * hh) / -dy;
    const s0 = uy * x0 - ux * y0;
    const tSurf = ux * x0 + uy * y0 - (this.c + this.etaAt(s0));
    const wall = tWall < Math.min(tSurf, tBottom);
    const tFall = Math.max(0, Math.min(tSurf, tWall, tBottom));
    P.len = Math.max(0, Math.min(tSurf, tBottom));
    P.wall = wall;
    P.s0 = s0;
    P.visible = true;
    P.tWall = tWall;

    const dv = P.flow * dt;
    this.vol += dv;
    this.drunkThisGlass = Math.max(0, this.drunkThisGlass - dv);
    // Foam ∝ impact speed √(2gh); a glass held at an angle (stream runs down the wall)
    // gives much less foam — exactly what bartenders do.
    const speed = Math.sqrt(2 * this.gIn * Math.max(tFall, 0.004));
    const foam = dv * POUR_FOAM * this.beer.foaminess * (0.25 + this.carb * 0.75) * (speed / 1.2) * (wall ? 0.35 : 1);
    this.addFoam(foam);
    this.cloud = Math.min(1, this.cloud + dv / (0.25 * this.area));
    this.cloudFront = 0;

    // Impact excites ripples at the point where the stream hits the surface.
    if (!wall && tSurf > 0) {
      const L = Math.max(this.sMax - this.sMin, 0.004);
      const xi = clamp((s0 - this.sMin) / L, 0, 1);
      const kick = (P.flow / this.area) * 0.35 * (speed / 1.2);
      for (let n = 1; n <= NMODES; n++) {
        this.v[n] -= kick * Math.cos(n * PI * xi) * (0.012 / n) * (Math.random() * 1.6 + 0.2);
      }
    }
    if (P.active && this.vol >= P.target) P.active = false;
  }

  stepSpill(dt, hw, hh, tx, ty) {
    const ux = this.ux, uy = this.uy;
    const N = 32;
    const dx = this.W / N;
    const g2 = 2 * this.gIn;
    let qT = 0, qB = 0;
    for (let i = 0; i < N; i++) {
      const x = -hw + (i + 0.5) * dx;
      const hRim = ux * x + uy * hh;
      const s = tx * x + ty * hh;
      const eta = this.etaAt(s);
      const headT = this.cf + eta - hRim;
      if (headT <= 0) continue;
      qT += Math.sqrt(g2 * headT) * dx;
      const headB = this.c + eta - hRim;
      if (headB > 0) qB += Math.sqrt(g2 * headB) * dx;
    }
    qT *= CD * DRINK_SCALE;
    qB *= CD * DRINK_SCALE;
    const dB = Math.min(this.vol, qB * dt);
    const dF = Math.min(this.foamVol, Math.max(0, qT - qB) * dt * 0.7);
    this.vol -= dB;
    this.foamVol -= dF;
    this.drunkThisGlass += dB;
    const A = this.area;
    this.outflow += (dB / dt / A - this.outflow) * Math.min(1, dt / 0.08);
    this.foamOutflow += (dF / dt / A - this.foamOutflow) * Math.min(1, dt / 0.08);
  }

  /** Energy-like measure of sloshing (for tests / audio). */
  waveEnergy() {
    let e = 0;
    for (let n = 1; n <= NMODES; n++) e += this.a[n] * this.a[n];
    return Math.sqrt(e);
  }
}
